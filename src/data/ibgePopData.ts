/**
 * Helper to normalize string for comparison
 */
function normalizeName(str: string): string {
  return str
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]/g, '')
    .trim();
}

const NORMALIZED_POP_CACHE: Record<string, number> = {};
Object.entries(IBGE_POPULATION_BY_NAME).forEach(([name, pop]) => {
  NORMALIZED_POP_CACHE[normalizeName(name)] = pop;
});

/**
 * Returns the official IBGE population for any São Paulo municipality by name or IBGE code
 */
export function getIbgePopulation(cityName?: string | null, codigoIbge?: string | null): number | undefined {
  if (codigoIbge) {
    const cleanCode = String(codigoIbge).replace(/\D/g, '');
    if (IBGE_POPULATION_MAP[cleanCode]) {
      return IBGE_POPULATION_MAP[cleanCode];
    }
    const cod6 = cleanCode.slice(0, 6);
    if (IBGE_POPULATION_MAP[cod6]) {
      return IBGE_POPULATION_MAP[cod6];
    }
  }

  if (!cityName) return undefined;

  const rawClean = cityName
    .replace(/^Prefeitura\s+de\s+/i, '')
    .replace(/^Prefeitura\s+/i, '')
    .trim();

  // Direct match
  if (IBGE_POPULATION_BY_NAME[rawClean] !== undefined) {
    return IBGE_POPULATION_BY_NAME[rawClean];
  }

  // Normalized match
  const norm = normalizeName(rawClean);
  if (NORMALIZED_POP_CACHE[norm] !== undefined) {
    return NORMALIZED_POP_CACHE[norm];
  }

  // Substring match
  for (const [cachedNorm, pop] of Object.entries(NORMALIZED_POP_CACHE)) {
    if (norm.includes(cachedNorm) || cachedNorm.includes(norm)) {
      return pop;
    }
  }

  return undefined;
}

/**
 * Returns formatted population string (e.g. "12.396.372 hab.") or fallback
 */
export function getIbgePopulationFormatted(cityName?: string | null, codigoIbge?: string | null): string {
  const pop = getIbgePopulation(cityName, codigoIbge);
  if (typeof pop === 'number' && pop > 0) {
    return `${pop.toLocaleString('pt-BR')} hab.`;
  }
  return '';
}
